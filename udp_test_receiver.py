import socket
import json


# ============================================================
# SMARTGEOAR
# TEST UDP RECEIVER
# ============================================================


# ============================================================
# 1. CONFIG
# ============================================================

HOST = "127.0.0.1"

PORT = 5052


# ============================================================
# 2. TẠO UDP SOCKET
# ============================================================

udp_socket = socket.socket(

    socket.AF_INET,

    socket.SOCK_DGRAM
)


# ============================================================
# 3. BIND PORT
# ============================================================

udp_socket.bind(

    (

        HOST,

        PORT
    )
)


print()

print("============================================")

print("SMARTGEOAR - UDP TEST RECEIVER")

print("============================================")

print()

print(

    f"Listening on {HOST}:{PORT}"
)

print()

print(

    "Đang chờ dữ liệu từ Role 1..."
)

print()


# ============================================================
# 4. RECEIVE LOOP
# ============================================================

while True:


    # ========================================================
    # 5. NHẬN DATA
    # ========================================================

    data, address = udp_socket.recvfrom(

        65535
    )


    # ========================================================
    # 6. BYTES -> STRING
    # ========================================================

    json_string = data.decode(

        "utf-8"
    )


    # ========================================================
    # 7. STRING -> JSON
    # ========================================================

    packet = json.loads(

        json_string
    )


    # ========================================================
    # 8. LẤY FRAME ID
    # ========================================================

    frame_id = packet.get(

        "frame_id",

        -1
    )


    # ========================================================
    # 9. LẤY HANDS
    # ========================================================

    detected_hands = packet.get(

        "hands",

        []
    )


    # ========================================================
    # 10. KHÔNG CÓ TAY
    # ========================================================

    if len(detected_hands) == 0:

        print(

            f"Frame {frame_id} | NO HAND"
        )

        continue


    # ========================================================
    # 11. CÓ TAY
    # ========================================================

    for hand_data in detected_hands:


        hand_name = hand_data.get(

            "hand",

            "Unknown"
        )


        gesture = hand_data.get(

            "gesture",

            "Unknown"
        )


        interaction = hand_data.get(

            "interaction",

            {}
        )


        x = interaction.get(

            "x",

            0
        )


        y = interaction.get(

            "y",

            0
        )


        pinch_ratio = hand_data.get(

            "pinch_ratio",

            0
        )


        # ====================================================
        # 12. PRINT
        # ====================================================

        print(

            f"Frame {frame_id:6}"

            f" | Hand: {hand_name:5}"

            f" | Gesture: {gesture:11}"

            f" | x={x:.4f}"

            f" | y={y:.4f}"

            f" | ratio={pinch_ratio:.4f}"
        )